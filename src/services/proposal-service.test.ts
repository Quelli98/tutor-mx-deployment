import { describe, expect, it, vi } from 'vitest';
import { createProposalService, PROPOSAL_PRESETS } from './proposal-service.js';
import type { PlanningStore } from './planning-store.js';
import type { QueryClient } from './allocation-queries.js';
import type { ScenarioService } from './scenario-service.js';

const START = '2030-10-07T08:00:00.000Z';
const END = '2030-10-14T08:00:00.000Z';
const SLOT_START = new Date('2030-10-08T08:00:00.000Z');
const SLOT_END = new Date('2030-10-08T10:00:00.000Z');

type RequirementRow = {
  id: number;
  courseId: number;
  courseCode: string;
  startsAt: Date;
  endsAt: Date;
  tutorsNeeded: number;
  hourlyRate: number | null;
  budget: number | null;
};
type ItemRow = {
  id?: number;
  sourceAllocationId: number | null;
  tutorId: number;
  tutorName: string;
  courseId: number;
  courseCode: string;
  startsAt: Date;
  endsAt: Date;
  allocatedHours: number;
  minimumMark: number;
  locked: boolean;
};
type CandidateRow = {
  tutorId: number;
  fullName: string;
  mark: number | null;
  weeklyLimit: number;
  usedHours: number;
  remainingHours: number;
  hasClash: boolean;
  isEligible: boolean;
  clashDetails: unknown[];
};
type ScenarioShape = {
  id: number;
  name: string;
  notes: string;
  startsAt: Date;
  endsAt: Date;
  status: string;
  version: number;
  baseLiveRevision: string;
  updatedAt: Date;
  updatedByName: string | null;
};
type DetailShape = { scenario: ScenarioShape; items: ItemRow[] };
type FakeState = {
  profile: boolean;
  requirements: RequirementRow[];
  live: ItemRow[];
  candidates: CandidateRow[];
  audits: unknown[][];
};

const requirement = (extra: Partial<RequirementRow> = {}): RequirementRow => ({
  id: 1,
  courseId: 1,
  courseCode: 'COMS',
  startsAt: SLOT_START,
  endsAt: SLOT_END,
  tutorsNeeded: 2,
  hourlyRate: 100,
  budget: 1000,
  ...extra,
});
const item = (extra: Partial<ItemRow> = {}): ItemRow => ({
  id: 1,
  sourceAllocationId: null,
  tutorId: 2,
  tutorName: 'Tutor Two',
  courseId: 1,
  courseCode: 'COMS',
  startsAt: SLOT_START,
  endsAt: SLOT_END,
  allocatedHours: 2,
  minimumMark: 50,
  locked: false,
  ...extra,
});
const candidate = (extra: Partial<CandidateRow> = {}): CandidateRow => ({
  tutorId: 2,
  fullName: 'Tutor Two',
  mark: 85,
  weeklyLimit: 10,
  usedHours: 0,
  remainingHours: 10,
  hasClash: false,
  isEligible: true,
  clashDetails: [],
  ...extra,
});
function fakeState(extra: Partial<FakeState> = {}): FakeState {
  return {
    profile: true,
    requirements: [requirement()],
    live: [],
    candidates: [
      candidate({ tutorId: 2, fullName: 'Tutor Two', mark: 80, usedHours: 0, remainingHours: 10 }),
      candidate({ tutorId: 3, fullName: 'Tutor Three', mark: 95, usedHours: 5, remainingHours: 5 }),
      candidate({ tutorId: 4, fullName: 'Busy Tutor', mark: 99, hasClash: true, isEligible: false }),
    ],
    audits: [],
    ...extra,
  };
}
function makeStore(state: FakeState): PlanningStore {
  const store: PlanningStore = {
    async query<Row>(sql: string, parameters: unknown[] = []) {
      if (sql.includes('FROM "Profile" WHERE "auth0Id"')) {
        return { rows: (state.profile ? [{ id: 7, fullName: 'Organiser One' }] : []) as unknown as Row[] };
      }
      if (sql.includes('FROM "StaffingRequirement" r JOIN "Course"')) {
        return { rows: state.requirements as unknown as Row[] };
      }
      if (sql.includes('FROM "Allocation" a JOIN "Profile" p') && sql.includes('sourceAllocationId')) {
        return { rows: state.live as unknown as Row[] };
      }
      if (sql.includes('WITH tutor_hours AS')) {
        return { rows: state.candidates as unknown as Row[] };
      }
      if (sql.includes('INSERT INTO "AuditEvent"')) {
        state.audits.push(parameters);
        return { rows: [] as Row[] };
      }
      throw new Error(`Unexpected proposal-service SQL: ${sql.slice(0, 80)}`);
    },
    async transaction<T>(work: (client: QueryClient) => Promise<T>) {
      return work(store);
    },
  };
  return store;
}
function detail(items: ItemRow[] = [], extra: Partial<ScenarioShape> = {}): DetailShape {
  return {
    scenario: {
      id: 10,
      name: 'Proposal',
      notes: 'Generated by BALANCED proposal preset.',
      startsAt: new Date(START),
      endsAt: new Date(END),
      status: 'DRAFT',
      version: 1,
      baseLiveRevision: 'revision',
      updatedAt: new Date('2030-10-01T00:00:00.000Z'),
      updatedByName: 'Organiser One',
      ...extra,
    },
    items,
  };
}
function scenarios(initial = detail()) {
  let current = initial;
  const get = vi.fn(async () => current);
  const create = vi.fn(async (_subject: string, input: Record<string, unknown>) => {
    current = detail([], { name: String(input.name), notes: String(input.notes), startsAt: new Date(String(input.startsAt)), endsAt: new Date(String(input.endsAt)) });
    return current;
  });
  const change = vi.fn(async (_subject: string, _id: number, input: Record<string, unknown>) => {
    if (input.action === 'duplicate') {
      current = detail(current.items, { id: 20, name: input.name, version: 1 });
      return current;
    }
    if (input.action === 'save-item') {
      const saved = input.item as Record<string, unknown>;
      const next = item({
        id: Number(saved.id ?? current.items.length + 1),
        tutorId: Number(saved.tutorId),
        courseId: Number(saved.courseId),
        startsAt: new Date(String(saved.startsAt)),
        endsAt: new Date(String(saved.endsAt)),
        allocatedHours: Number(saved.allocatedHours),
        minimumMark: Number(saved.minimumMark),
      });
      const existing = current.items.findIndex(x => x.id === next.id);
      const nextItems = [...current.items];
      if (existing >= 0) nextItems[existing] = next;
      else nextItems.push(next);
      current = { ...current, scenario: { ...current.scenario, version: current.scenario.version + 1 }, items: nextItems };
    }
    return current;
  });
  return { service: { get, create, change } as unknown as ScenarioService, get, create, change };
}
const input = (extra: Record<string, unknown> = {}) => ({ name: 'October proposal', startsAt: START, endsAt: END, preset: 'BALANCED', ...extra });

describe('proposal service generation and explanations', () => {
  it('builds a deterministic proposal, explains skips, tracks spend/workload and shortage', async () => {
    const state = fakeState();
    const scenario = scenarios();
    const service = createProposalService(makeStore(state), scenario.service);
    const result = await service.preview('auth|org', input());
    expect(result.preset).toBe('BALANCED');
    expect(result.assignments).toHaveLength(2);
    expect(result.assignments.map(x => x.tutorId).sort()).toEqual([2, 3]);
    expect(result.metrics).toMatchObject({ proposedAssignments: 2, coveredTutorHours: 4, shortageHours: 0, projectedAddedSpend: 400 });
    expect(result.metrics.workload).toEqual([
      { tutorId: 2, tutorName: 'Tutor Two', hours: 2 },
      { tutorId: 3, tutorName: 'Tutor Three', hours: 2 },
    ]);
    expect(result.assignments[0]!.explanation.some(x => x.hardFailures.includes('schedule-clash'))).toBe(true);
    expect(result.assignments[1]!.explanation.some(x => x.hardFailures.includes('already-assigned-to-requirement'))).toBe(true);
  });

  it('compares every preset and exercises budget, strongest-match and fair-workload ordering', async () => {
    const state = fakeState({
      requirements: [
        requirement({ id: 1, courseId: 1, courseCode: 'EXPENSIVE', tutorsNeeded: 1, hourlyRate: 200 }),
        requirement({ id: 2, courseId: 2, courseCode: 'CHEAP', startsAt: new Date('2030-10-09T08:00:00Z'), endsAt: new Date('2030-10-09T10:00:00Z'), tutorsNeeded: 1, hourlyRate: 50 }),
      ],
    });
    const service = createProposalService(makeStore(state), scenarios().service);
    const compared = await service.compare('auth|org', { name: 'Strategies', startsAt: START, endsAt: END });
    expect(compared.map(x => x.preset)).toEqual(PROPOSAL_PRESETS);
    expect(compared).toHaveLength(4);
    const budget = compared.find(x => x.preset === 'BUDGET_AWARE')!;
    expect(budget.assignments[0]!.courseCode).toBe('CHEAP');
    expect(compared.find(x => x.preset === 'STRONGEST_MATCH')!.assignments[0]!.explanation.some(x => x.factors.some(f => f.includes('higher course mark')))).toBe(true);
    expect(compared.find(x => x.preset === 'FAIR_WORKLOAD')!.assignments[0]!.explanation.some(x => x.factors.some(f => f.includes('unused weekly capacity')))).toBe(true);
  });

  it('reports shortages, ignores invalid-duration requirements and counts live coverage', async () => {
    const live = item({ id: 90, sourceAllocationId: 90, tutorId: 8, tutorName: 'Live Tutor', startsAt: SLOT_START, endsAt: new Date('2030-10-08T09:00:00Z'), allocatedHours: 1 });
    const state = fakeState({
      live: [live],
      candidates: [],
      requirements: [
        requirement({ tutorsNeeded: 2 }),
        requirement({ id: 2, courseId: 2, courseCode: 'LONG', startsAt: new Date('2030-10-10T00:00:00Z'), endsAt: new Date('2030-10-10T09:00:00Z'), tutorsNeeded: 1 }),
      ],
    });
    const result = await createProposalService(makeStore(state), scenarios().service).preview('auth|org', input());
    expect(result.assignments).toEqual([]);
    expect(result.shortages).toEqual([{ requirementId: 1, courseCode: 'COMS', hours: 3 }]);
    expect(result.metrics.shortageHours).toBe(3);
  });

  it('generates a scenario, saves assignments and can explain generated choices', async () => {
    const state = fakeState({ requirements: [requirement({ tutorsNeeded: 1 })] });
    const scenario = scenarios();
    const service = createProposalService(makeStore(state), scenario.service);
    const generated = await service.generate('auth|org', input({ preset: 'FAIR_WORKLOAD' }));
    expect(scenario.create).toHaveBeenCalledOnce();
    expect(scenario.change).toHaveBeenCalledWith('auth|org', 10, expect.objectContaining({ action: 'save-item', version: 1 }));
    expect(generated.items).toHaveLength(1);
    const explanation = await service.explain('auth|org', generated.scenario.id);
    expect(explanation.preset).toBe('FAIR_WORKLOAD');
    expect(explanation.assignments).toHaveLength(1);
    expect(explanation.assignments[0]!.explanation.some(x => x.chosen)).toBe(true);
    expect(explanation.assignments[0]!.explanation.some(x => !x.eligible && x.reason.startsWith('Why not:'))).toBe(true);
  });

  it('duplicates a matching base scenario before generation and refuses mismatched bases', async () => {
    const scenario = scenarios(detail([], { notes: 'Base', version: 4 }));
    const state = fakeState({ requirements: [] });
    const service = createProposalService(makeStore(state), scenario.service);
    const generated = await service.generate('auth|org', input({ baseScenarioId: 10 }));
    expect(scenario.change).toHaveBeenCalledWith('auth|org', 10, expect.objectContaining({ action: 'duplicate', version: 4 }));
    expect(generated.scenario.id).toBe(20);

    const mismatch = scenarios(detail([], { startsAt: new Date('2030-10-08T00:00:00Z') }));
    await expect(createProposalService(makeStore(state), mismatch.service).preview('auth|org', input({ baseScenarioId: 10 }))).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
  });

  it('fails safely if duplicate or save-item unexpectedly returns a deleted result', async () => {
    const state = fakeState({ requirements: [requirement({ tutorsNeeded: 1 })] });
    const base = detail([], { version: 2 });
    const duplicateFailure = {
      get: vi.fn().mockResolvedValue(base),
      create: vi.fn(),
      change: vi.fn().mockResolvedValue({ deleted: true }),
    } as unknown as ScenarioService;
    await expect(createProposalService(makeStore(state), duplicateFailure).generate('auth|org', input({ baseScenarioId: 10 }))).rejects.toMatchObject({ code: 'PROPOSAL_SCENARIO_FAILED' });

    const saveFailure = {
      get: vi.fn().mockResolvedValue(base),
      create: vi.fn().mockResolvedValue(detail()),
      change: vi.fn().mockResolvedValue({ deleted: true }),
    } as unknown as ScenarioService;
    await expect(createProposalService(makeStore(state), saveFailure).generate('auth|org', input())).rejects.toMatchObject({ code: 'PROPOSAL_SCENARIO_FAILED' });
  });
});

describe('proposal service manual adjustment and validation', () => {
  it('manually changes an eligible unlocked assignment and writes an audit record', async () => {
    const state = fakeState({ requirements: [] });
    const scenario = scenarios(detail([item()]));
    const service = createProposalService(makeStore(state), scenario.service);
    const changed = await service.adjust('auth|org', 10, { version: 1, itemId: 1, tutorId: 3, reason: 'Balances the workload' });
    expect(changed.scenario.version).toBe(2);
    expect(scenario.change).toHaveBeenCalledWith('auth|org', 10, expect.objectContaining({ action: 'save-item', version: 1 }));
    expect(state.audits).toHaveLength(1);
  });

  it('rejects missing, locked, ineligible, clashing and over-capacity adjustments', async () => {
    const baseState = fakeState({ requirements: [] });
    await expect(createProposalService(makeStore(baseState), scenarios(detail([])).service).adjust('auth|org', 10, { version: 1, itemId: 99, tutorId: 3, reason: 'Valid reason' })).rejects.toMatchObject({ code: 'PROPOSAL_ITEM_NOT_FOUND' });
    await expect(createProposalService(makeStore(baseState), scenarios(detail([item({ locked: true })])).service).adjust('auth|org', 10, { version: 1, itemId: 1, tutorId: 3, reason: 'Valid reason' })).rejects.toMatchObject({ code: 'ITEM_LOCKED' });

    const ineligible = fakeState({ requirements: [], candidates: [candidate({ tutorId: 3, isEligible: false, mark: 20 })] });
    await expect(createProposalService(makeStore(ineligible), scenarios(detail([item()])).service).adjust('auth|org', 10, { version: 1, itemId: 1, tutorId: 3, reason: 'Valid reason' })).rejects.toMatchObject({ code: 'PROPOSAL_RULE_FAILED' });

    const clashItem = item({ id: 2, tutorId: 3, tutorName: 'Tutor Three', startsAt: new Date('2030-10-08T09:00:00Z'), endsAt: new Date('2030-10-08T11:00:00Z') });
    await expect(createProposalService(makeStore(baseState), scenarios(detail([item(), clashItem])).service).adjust('auth|org', 10, { version: 1, itemId: 1, tutorId: 3, reason: 'Valid reason' })).rejects.toMatchObject({ code: 'PROPOSAL_RULE_FAILED' });

    const capacity = fakeState({ requirements: [], candidates: [candidate({ tutorId: 3, remainingHours: 1 })] });
    await expect(createProposalService(makeStore(capacity), scenarios(detail([item()])).service).adjust('auth|org', 10, { version: 1, itemId: 1, tutorId: 3, reason: 'Valid reason' })).rejects.toMatchObject({ code: 'PROPOSAL_RULE_FAILED' });
  });

  it('validates role, fields, preset, name, reason, identifiers and planning window', async () => {
    const state = fakeState();
    const service = createProposalService(makeStore(state), scenarios().service);
    await expect(service.preview('auth|org', input({ extra: true }))).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
    await expect(service.preview('auth|org', input({ preset: 'UNKNOWN' }))).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
    await expect(service.preview('auth|org', input({ name: '' }))).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
    await expect(service.preview('auth|org', input({ startsAt: '2020-01-01T00:00:00Z', endsAt: '2020-01-02T00:00:00Z' }))).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
    await expect(service.preview('auth|org', input({ endsAt: '2031-01-01T00:00:00Z' }))).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
    await expect(service.adjust('auth|org', 10, { version: 1, itemId: 1, tutorId: 3, reason: 'x' })).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });
    await expect(service.explain('auth|org', 0)).rejects.toMatchObject({ code: 'VALIDATION_ERROR' });

    const forbidden = createProposalService(makeStore(fakeState({ profile: false })), scenarios().service);
    await expect(forbidden.preview('auth|student', input())).rejects.toMatchObject({ code: 'FORBIDDEN' });
  });

  it('protects proposal context size limits', async () => {
    const tooManyRequirements = Array.from({ length: 201 }, (_, index) => requirement({ id: index + 1 }));
    await expect(createProposalService(makeStore(fakeState({ requirements: tooManyRequirements })), scenarios().service).preview('auth|org', input())).rejects.toMatchObject({ code: 'PROPOSAL_TOO_LARGE' });
    const tooManyLive = Array.from({ length: 201 }, (_, index) => item({ id: index + 1, sourceAllocationId: index + 1 }));
    await expect(createProposalService(makeStore(fakeState({ live: tooManyLive })), scenarios().service).preview('auth|org', input())).rejects.toMatchObject({ code: 'PROPOSAL_TOO_LARGE' });
  });

  it('defaults explanation preset to balanced when scenario notes do not contain a preset', async () => {
    const state = fakeState({ requirements: [] });
    const scenario = scenarios(detail([item()], { notes: 'Manually created scenario' }));
    const explained = await createProposalService(makeStore(state), scenario.service).explain('auth|org', 10);
    expect(explained.preset).toBe('BALANCED');
  });
});
